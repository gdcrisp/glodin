#!/usr/bin/env python3
"""Regenerate the private C-shim declarations; no header ABI layouts are copied."""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
types = {"void": "void", "int": "i32", "unsigned": "u32", "int64_t": "i64",
         "uint64_t": "u64", "size_t": "uint", "double": "f64", "char": "u8",
         "unsigned char": "u8", "ERL_NIF_TERM": "Term", "ErlNifEnv": "Env",
         "ErlNifPid": "Pid", "ErlNifMonitor": "Monitor", "ErlNifEvent": "Event",
         "ErlNifResourceDtor": "Callback", "ErlNifResourceDown": "Callback",
         "ErlNifResourceStop": "Callback"}

def type_name(value):
    value = value.replace("const", "").strip()
    pointers = value.count("*")
    base = value.replace("*", "").strip()
    if base == "void" and pointers:
        return "^" * (pointers - 1) + "rawptr"
    if base.startswith("ErlNifResource"):
        return "rawptr"
    return "^" * pointers + types[base]

lines = ['// Generated by scripts/generate_sys.py.\npackage sys\n',
         'Env :: struct {}\nTerm :: distinct uintptr\nPid :: struct { handle: uintptr }\nMonitor :: struct {}\n',
         'when ODIN_OS == .Windows { Event :: rawptr } else { Event :: i32 }\n',
         'foreign import shim "glodin_shim:shim.o"\n',
         '@(default_calling_convention="c", link_prefix="glodin_")\nforeign shim {']
for line in (root / "priv/c/glodin.h").read_text().splitlines():
    match = re.match(r"(.+?)\s*(glodin_\w+)\((.*)\);$", line)
    if not match:
        continue
    result, name, parameters = match.groups()
    params = []
    if parameters != "void":
        for i, param in enumerate(parameters.split(",")):
            match_arg = re.match(r"(.*?)\b([a-zA-Z_]\w*)$", param.strip())
            arg_type, _ = match_arg.groups()
            params.append(f"p{i}: {type_name(arg_type)}")
    ret = type_name(result)
    suffix = "" if ret == "void" else " -> " + ret
    lines.append(f"\t{name.removeprefix('glodin_')} :: proc({', '.join(params)}){suffix} ---")
lines.append("}\n")
dest = root / "priv/odin/sys/sys.odin"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(lines))
