-module(glodin_conformance_assertions).
-export([run/0, load_data/0]).
-define(N, glodin_conformance_checks_ffi).

load_data() -> 29.

badarg(F) ->
    try F() of Result -> erlang:error({expected_badarg, Result})
    catch error:badarg -> ok end.

run() ->
    0 = ?N:load_value(),
    -128 = ?N:echo_i8(-128),
    127 = ?N:echo_i8(127),
    badarg(fun() -> ?N:echo_i8(128) end),
    badarg(fun() -> ?N:echo_i8(-129) end),
    badarg(fun() -> ?N:echo_i8(not_an_integer) end),
    U64 = (1 bsl 64) - 1,
    U64 = ?N:echo_u64(U64),
    badarg(fun() -> ?N:echo_u64(-1) end),
    badarg(fun() -> ?N:echo_u64(1 bsl 64) end),
    I128 = -(1 bsl 127),
    I128 = ?N:echo_i128(I128),
    Big = -(1 bsl 1024) + 123,
    Big = ?N:echo_big(Big),
    TwiceBig = Big * 2,
    TwiceBig = ?N:double_big(Big),
    0 = ?N:echo_big(0),
    123 = ?N:echo_big(123),
    -345 = ?N:echo_big(-345),
    1.25 = ?N:echo_float(1.25),
    badarg(fun() -> ?N:echo_float(1) end),
    Text = <<"hello ", 16#1f680/utf8>>,
    Text = ?N:echo_string(Text),
    badarg(fun() -> ?N:echo_string(<<255>>) end),
    <<255,0>> = ?N:echo_bytes(<<255,0>>),
    badarg(fun() -> ?N:echo_bytes(<<1:1>>) end),
    [] = ?N:echo_list([]),
    [1,-2,3] = ?N:echo_list([1,-2,3]),
    badarg(fun() -> ?N:echo_list([1|2]) end),
    badarg(fun() -> ?N:echo_list([1,no]) end),
    Person = {person, <<"Ada">>, 36},
    Person = ?N:echo_person(Person),
    badarg(fun() -> ?N:echo_person({wrong, <<"Ada">>, 36}) end),
    green = ?N:echo_colour(green),
    badarg(fun() -> ?N:echo_colour(purple) end),
    {circle, 2.5} = ?N:echo_shape({circle,2.5}),
    {rectangle, 2.0, 3.0} = ?N:echo_shape({rectangle,2.0,3.0}),
    {1,<<"one">>} = ?N:echo_pair({1,<<"one">>}),
    #{enabled := true,size := 10} = ?N:echo_settings(#{enabled => true,size => 10}),
    {ok,42} = ?N:echo_result({ok,42}),
    {error,<<"reason">>} = ?N:echo_result({error,<<"reason">>}),
    {some,42} = ?N:echo_option({some,42}),
    none = ?N:echo_option(none),
    Json = ?N:echo_json(<<"{\"name\":\"Ada\",\"age\":36}">>),
    #{<<"name">> := <<"Ada">>, <<"age">> := 36} = json:decode(Json),
    badarg(fun() -> ?N:echo_json(<<"{broken}">>) end),
    badarg(fun() -> ?N:echo_json(<<255>>) end),
    badarg(fun() -> ?N:echo_json(<<"{\"age\":\"wrong\"}">>) end),
    badarg(fun() -> ?N:echo_json(<<"{} {}">>) end),
    84 = ?N:renamed(42),
    7 = ?N:dirty_io(7),
    C = ?N:counter_new(0),
    1 = ?N:counter_increment(C),
    1 = ?N:counter_read(C),
    Parent = self(),
    [spawn(fun() -> [?N:counter_increment(C) || _ <- lists:seq(1,100)], Parent ! done end) || _ <- lists:seq(1,8)],
    [receive done -> ok after 5000 -> error(counter_timeout) end || _ <- lists:seq(1,8)],
    801 = ?N:counter_read(C),
    801 = ?N:counter_dynamic(C),
    badarg(fun() -> ?N:counter_read(make_ref()) end),
    Ref = ?N:new_reference(),
    true = is_reference(Ref),
    Self = self(),
    Self = ?N:get_self(),
    true = ?N:send_message(self(), {hello,42}),
    receive {hello,42} -> ok after 1000 -> error(send_timeout) end,
    true = ?N:background(self(), 21),
    receive 42 -> ok after 5000 -> error(job_timeout) end,
    true = ?N:pool_enqueue(self(), 1),
    true = ?N:pool_enqueue(self(), 2),
    [receive pool_started -> ok after 5000 -> error(pool_start_timeout) end || _ <- [1,2]],
    [true = ?N:pool_enqueue(self(), N) || N <- [3,4,5,6]],
    false = ?N:pool_enqueue(self(), 7),
    nil = ?N:pool_release(),
    nil = ?N:pool_close(),
    [receive pool_started -> ok after 5000 -> error(pool_queue_timeout) end || _ <- [3,4,5,6]],
    [2,4,6,8,10,12] = lists:sort([receive Result when is_integer(Result) -> Result
        after 5000 -> error(pool_result_timeout) end || _ <- lists:seq(1,6)]),
    false = ?N:pool_enqueue(self(), 8),
    nil = ?N:pool_close(),
    try ?N:raise_error() of _ -> error(expected_exception)
    catch error:deliberate -> ok end,
    12 = ?N:echo_positive(12),
    badarg(fun() -> ?N:echo_positive(0) end),
    <<1,2,255>> = ?N:owned_bytes(<<1,2,255>>),
    #{nested := [1,{ok,<<"value">>}]} = ?N:environment_copy(#{nested => [1,{ok,<<"value">>}]}),
    <<1,2,255>> = ?N:resource_bytes(<<1,2,255>>),
    true = ?N:check_low_level(1.0),
    false = ?N:check_low_level(<<"no">>),
    true = ?N:check_allocator(),
    NativeRecord = {native_record,42},
    NativeRecord = ?N:echo_record(NativeRecord),
    42 = ?N:echo_untagged(42),
    <<"text">> = ?N:echo_untagged(<<"text">>),
    badarg(fun() -> ?N:echo_untagged(false) end),
    AtomText = <<16#1f680/utf8>>,
    AtomText = ?N:atom_roundtrip(AtomText),
    5 = ?N:iterate_values([1,2,3],#{a => 1,b => 2}),
    42 = ?N:yielding(41),
    true = register(glodin_conformance_runner,self()),
    Term = {nested,[1,2],#{key => <<"value">>}},
    true = ?N:check_term_operations(Term,erlang:phash2(Term)),
    true = unregister(glodin_conformance_runner),
    <<1,2,3>> = ?N:iolist_bytes([1,[<<2>>,3]]),
    badarg(fun() -> ?N:iolist_bytes([256]) end),
    <<2>> = ?N:sub_bytes(<<1,2,3>>,1,1),
    <<>> = ?N:sub_bytes(<<1,2,3>>,3,0),
    badarg(fun() -> ?N:sub_bytes(<<1,2,3>>,1,3) end),
    badarg(fun() -> ?N:sub_bytes(<<1>>, -1, 0) end),
    badarg(fun() -> ?N:sub_bytes(<<1:1>>,0,0) end),
    Target = spawn(fun() -> receive stop -> ok end end),
    Watcher = spawn(fun() ->
        R = ?N:watch_process(Parent,Target),
        Parent ! watcher_ready,
        receive release -> true = is_reference(R), ok end
    end),
    receive watcher_ready -> ok after 1000 -> error(watcher_timeout) end,
    receive observed_destroyed -> error(retained_resource_destroyed) after 0 -> ok end,
    Target ! stop,
    receive observed_down -> ok after 5000 -> error(monitor_timeout) end,
    Watcher ! release,
    receive observed_destroyed -> ok after 5000 -> error(destructor_timeout) end,
    CancelTarget = spawn(fun() -> receive stop -> ok end end),
    CancelMonitor = monitor(process,CancelTarget),
    CancelHolder = spawn(fun() ->
        R2 = ?N:watch_then_cancel(Parent,CancelTarget),
        Parent ! cancel_ready,
        receive release -> true = is_reference(R2), ok end
    end),
    receive cancel_ready -> ok after 1000 -> error(cancel_timeout) end,
    CancelTarget ! stop,
    receive {'DOWN',CancelMonitor,process,CancelTarget,_} -> ok after 1000 -> error(exit_timeout) end,
    receive observed_down -> error(monitor_not_cancelled) after 100 -> ok end,
    CancelHolder ! release,
    receive observed_destroyed -> ok after 5000 -> error(cancel_destructor_timeout) end,
    Selectable = ?N:select_start(),
    receive {select,Selectable,SelectRef,ready_input} when is_reference(SelectRef) -> ok
    after 5000 -> error(select_ready_timeout) end,
    true = ?N:select_stop(Selectable),
    receive select_stopped -> ok after 5000 -> error(select_stop_timeout) end,
    io:format("Glodin conformance checks passed.~n"),
    ok.
